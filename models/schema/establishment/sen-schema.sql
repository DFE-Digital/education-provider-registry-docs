-- Shared by fresh builds and the additive local SEN migration.
CREATE TABLE IF NOT EXISTS establishment.sen (
    sen_id integer GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1) PRIMARY KEY,
    code text NOT NULL UNIQUE,
    name text NOT NULL
);

CREATE TABLE IF NOT EXISTS establishment.establishment_sen (
    establishment_sen_id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    establishment_id uuid NOT NULL
        REFERENCES establishment.establishment (establishment_id),
    sen_id integer NOT NULL REFERENCES establishment.sen (sen_id),
    UNIQUE (establishment_id, sen_id)
);

CREATE INDEX IF NOT EXISTS establishment_sen_by_sen
    ON establishment.establishment_sen (sen_id, establishment_id);
